"""Fail-closed gate for immutable dataset manifests (task DAT-001).

Every canonical committed dataset carries a manifest under ``data/manifests/``.
This gate proves each manifest is honest and each result can cite an exact
dataset digest. It fails closed (RED) when a dataset is unknown, unlicensed,
carries no evidence class, or whose on-disk bytes no longer match the recorded
checksum.

Checks, per manifest:
  1. schema-valid against schemas/dataset_manifest.schema.json;
  2. ``license`` is a *granted* license (not empty / UNKNOWN / UNLICENSED /
     NONE / TBD / PUBLIC_NO_LICENSE) -> else RED;
  3. ``evidence_class`` is one of the closed vocabulary -> else RED;
  4. dataset-level ``checksum.value`` == dataset_digest(files) -> else RED;
  5. for every file in ``files[]`` that is present on disk, sha256 is recomputed
     and must equal the recorded ``checksum_sha256`` -> else RED (tamper).
     Absent files (large binaries) are reported but do not fail closed.

Exit codes::

    0  — every manifest is valid and every on-disk dataset matches
    1  — at least one manifest is invalid / unlicensed / classless / tampered
    2  — schema or manifest directory missing (misconfiguration)

Note: run against the live repo this gate is EXPECTED to be RED while real,
unlicensed vendor/market data (data/askar*, data/raw/binance*) remains
committed to this synthetic-only / NO_DEPLOY repository. That RED is the
governance alarm, not a bug — see docs/DATASET_MANIFEST_POLICY.md.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

try:
    import jsonschema
except ModuleNotFoundError as exc:  # DS-18: fail cleanly, never raw traceback
    print(json.dumps({"status": "ERROR", "error": f"missing dependency: {exc.name}"}))
    sys.exit(2)

ROOT = Path(__file__).resolve().parents[2]
SCHEMA_PATH = ROOT / "schemas" / "dataset_manifest.schema.json"
DEFAULT_MANIFEST_DIR = ROOT / "data" / "manifests"

# A license value that does NOT grant redistribution rights. Any of these
# (case-insensitive) trips the fail-closed gate.
UNLICENSED_TOKENS = {
    "",
    "unknown",
    "unlicensed",
    "none",
    "null",
    "tbd",
    "n/a",
    "public_no_license",
    "no_license",
    "proprietary_unverified",
}

ALLOWED_EVIDENCE_CLASSES = {"FACT", "MEASURED", "SIMULATION", "HYPOTHESIS", "RETIRED"}

# Evidence classes that assert *real-world provenance* — data that was measured
# or captured from the world, not generated by this repository. A manifest that
# claims one of these while its own body still carries synthetic-origin markers
# is a provenance lie and must fail closed (DS-10).
REAL_WORLD_EVIDENCE_CLASSES = {"FACT", "MEASURED"}

# Synthetic-origin markers, read from the real committed manifests
# (data/manifests/*.json). Any one of these contradicts a FACT/MEASURED claim.
SYNTHETIC_ORIGINS = {"repository_generated"}
SYNTHETIC_RETRIEVAL_TIMES = {"SYNTHETIC_GENERATED"}
# A generator-script invocation in the free-form `query` field, e.g.
# "python scripts/generate_sample_ohlcv.py --seed 42".
_GENERATOR_QUERY_RE = re.compile(r"python\s+[\w./\-]+\.py|scripts/generate", re.IGNORECASE)

_READ_CHUNK = 1 << 20


def synthetic_origin_markers(doc: dict) -> list[str]:
    """Return the synthetic-origin markers present in a manifest body (empty == none).

    These are the provable, self-contradicting signals that a dataset was
    generated by this repository rather than measured from the world:
      * ``source.origin`` in {repository_generated};
      * ``retrieval_time`` in {SYNTHETIC_GENERATED};
      * a generator-script invocation (``python …/generate_*.py`` or a
        ``scripts/generate`` path) in the free-form ``query`` field.
    """
    markers: list[str] = []

    origin = str((doc.get("source") or {}).get("origin", "")).strip()
    if origin.lower() in {o.lower() for o in SYNTHETIC_ORIGINS}:
        markers.append(f"source.origin={origin!r}")

    retrieval = str(doc.get("retrieval_time", "")).strip()
    if retrieval.upper() in {r.upper() for r in SYNTHETIC_RETRIEVAL_TIMES}:
        markers.append(f"retrieval_time={retrieval!r}")

    query = str(doc.get("query", ""))
    if _GENERATOR_QUERY_RE.search(query):
        markers.append(f"query has generator script ({query!r})")

    return markers


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as fh:
        for chunk in iter(lambda: fh.read(_READ_CHUNK), b""):
            h.update(chunk)
    return h.hexdigest()


def dataset_digest(files: list[dict]) -> str:
    """Deterministic dataset-level digest.

    sha256 over the sorted ``"{path}  {file-sha256}\\n"`` lines. Must stay in
    lockstep with scripts that emit manifests.
    """
    lines = sorted(f"{f['path']}  {f['checksum_sha256']}\n" for f in files)
    return hashlib.sha256("".join(lines).encode("utf-8")).hexdigest()


def check_manifest(
    doc: dict,
    rel: str,
    validator: jsonschema.protocols.Validator,
    root: Path,
) -> list[str]:
    """Return a list of failure strings for one manifest (empty == OK)."""
    problems: list[str] = []

    schema_errors = sorted(validator.iter_errors(doc), key=lambda e: list(e.path))
    if schema_errors:
        for err in schema_errors:
            loc = "/".join(str(p) for p in err.path) or "<root>"
            problems.append(f"{rel}: schema: {loc}: {err.message}")
        # Schema-invalid docs may lack the fields the checks below rely on.
        return problems

    # 2. license must be a granted license.
    license_value = str(doc.get("license", "")).strip()
    if license_value.lower() in UNLICENSED_TOKENS:
        problems.append(
            f"{rel}: UNLICENSED — license={license_value!r} is not a granted "
            f"license (fail-closed). id={doc.get('id')!r}"
        )

    # 3. evidence_class must be in the closed vocabulary (schema also enforces).
    ec = doc.get("evidence_class")
    if ec not in ALLOWED_EVIDENCE_CLASSES:
        problems.append(f"{rel}: unknown evidence_class={ec!r}")

    # 3b. provenance consistency (DS-10): a real-world class (FACT/MEASURED)
    # is INCOMPATIBLE with synthetic-origin markers in the manifest's own body.
    # Relabeling repository-generated / simulation data as measured real-world
    # data is a provable lie that contradicts source.origin / retrieval_time /
    # query — fail closed instead of trusting the label.
    if ec in REAL_WORLD_EVIDENCE_CLASSES:
        markers = synthetic_origin_markers(doc)
        if markers:
            problems.append(
                f"{rel}: EVIDENCE-CLASS INVERSION — evidence_class={ec!r} asserts "
                f"real-world provenance, but the manifest body carries "
                f"synthetic-origin markers [{'; '.join(markers)}]. Synthetic/"
                f"repository-generated data cannot be a measured real-world FACT "
                f"(fail-closed). id={doc.get('id')!r}"
            )

    files = doc.get("files") or []

    # 4. dataset-level checksum integrity.
    recorded = str(doc.get("checksum", {}).get("value", ""))
    computed = dataset_digest(files)
    if recorded != computed:
        problems.append(
            f"{rel}: dataset checksum mismatch — manifest={recorded} "
            f"computed(from files[])={computed}"
        )

    # 5. per-file on-disk checksum recompute.
    for entry in files:
        fpath = root / entry["path"]
        if not fpath.exists():
            print(f"  info: {rel}: {entry['path']} absent on disk (large binary, checksum trusted)")
            continue
        actual = sha256_file(fpath)
        if actual != entry["checksum_sha256"]:
            problems.append(
                f"{rel}: CHECKSUM MISMATCH — {entry['path']}: "
                f"manifest={entry['checksum_sha256']} disk={actual}"
            )
        actual_bytes = fpath.stat().st_size
        if actual_bytes != entry["bytes"]:
            problems.append(
                f"{rel}: byte-size mismatch — {entry['path']}: "
                f"manifest={entry['bytes']} disk={actual_bytes}"
            )

    return problems


def run(manifest_dir: Path, root: Path, schema_path: Path) -> int:
    if not schema_path.exists():
        print(f"schema not found: {schema_path}", file=sys.stderr)
        return 2
    if not manifest_dir.exists():
        print(f"manifest directory not found: {manifest_dir}", file=sys.stderr)
        return 2

    schema = json.loads(schema_path.read_text(encoding="utf-8"))
    jsonschema.Draft202012Validator.check_schema(schema)
    validator = jsonschema.Draft202012Validator(schema)

    manifests = sorted(manifest_dir.glob("*.json"))
    if not manifests:
        print(f"no dataset manifests found under {manifest_dir}", file=sys.stderr)
        return 1

    all_problems: list[str] = []
    flagged: list[str] = []
    seen_ids: dict[str, str] = {}

    for mpath in manifests:
        rel = mpath.name
        try:
            doc = json.loads(mpath.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            all_problems.append(f"{rel}: invalid JSON ({exc})")
            continue

        did = doc.get("id")
        if isinstance(did, str):
            if did in seen_ids:
                all_problems.append(f"{rel}: duplicate id {did!r} (also in {seen_ids[did]})")
            else:
                seen_ids[did] = rel

        all_problems.extend(check_manifest(doc, rel, validator, root))

        for flag in doc.get("flags", []) or []:
            flagged.append(f"{rel}: FLAG {flag}")

    if flagged:
        print("=" * 72)
        print("GOVERNANCE FLAGS (real/unlicensed data in a synthetic-only repo):")
        for line in flagged:
            print(f"  ! {line}")
        print("=" * 72)

    if all_problems:
        print(
            f"\nDataset manifest gate FAILED (RED): {len(all_problems)} problem(s).",
            file=sys.stderr,
        )
        for line in all_problems:
            print(f"  - {line}", file=sys.stderr)
        return 1

    print(
        f"\nDataset manifest gate PASSED: {len(manifests)} manifest(s) valid, "
        f"{len(seen_ids)} unique dataset id(s), on-disk checksums verified."
    )
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Validate immutable dataset manifests (DAT-001).")
    parser.add_argument(
        "--manifest-dir",
        type=Path,
        default=DEFAULT_MANIFEST_DIR,
        help="Directory of *.json manifests (default: data/manifests).",
    )
    parser.add_argument(
        "--root",
        type=Path,
        default=ROOT,
        help="Repo root used to resolve file paths (default: repo root).",
    )
    parser.add_argument(
        "--schema", type=Path, default=SCHEMA_PATH, help="Path to dataset_manifest.schema.json."
    )
    args = parser.parse_args(argv)
    return run(args.manifest_dir.resolve(), args.root.resolve(), args.schema.resolve())


if __name__ == "__main__":
    raise SystemExit(main())
