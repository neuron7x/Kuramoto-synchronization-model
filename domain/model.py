@dataclass(frozen=True, slots=True)
class AAREvent:
    """Acceptor of Action Result event for feedback loop.

    Captures the outcome of an action for learning and adaptation.
    Used to compute prediction errors and drive controller updates.

    Attributes:
        action_id: ID of the action this event relates to.
        prediction: Predicted outcome.
        outcome: Actual outcome.
        error: Computed prediction error.
        error_sign: Direction of error (+1 better, -1 worse, 0 equal).
        error_magnitude: Normalized magnitude of error.
        strategy_id: Strategy that initiated the action.
        timestamp: When the outcome was recorded.
        context_snapshot: System state at action time.
        metadata: Additional event metadata.
    """

    action_id: str
    prediction: float = 0.0
    outcome: float = 0.0
    error: float = 0.0
    error_sign: int = 0
    error_magnitude: float = 0.0
    strategy_id: StrategyId | None = None
    timestamp: datetime = field(default_factory=_utc_now)
    context_snapshot: Mapping[str, Any] = field(default_factory=dict)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.error_sign not in (-1, 0, 1):
            raise ValueError("error_sign must be -1, 0, or 1")
        if self.error_magnitude < 0:
            raise ValueError("error_magnitude cannot be negative")
        object.__setattr__(
            self, "context_snapshot", _freeze_mapping(self.context_snapshot)
        )
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "timestamp", _ensure_utc(self.timestamp))

    @classmethod
    def from_prediction_outcome(
        cls,
        action_id: str,
        prediction: float,
        outcome: float,
        *,
        strategy_id: StrategyId | None = None,
        scale: float = 1.0,
        context_snapshot: Mapping[str, Any] | None = None,
    ) -> "AAREvent":
        """Create AAR event from prediction and outcome values.

        Computes error metrics based on the difference between
        predicted and actual outcomes.

        Args:
            action_id: ID of the action.
            prediction: Predicted value.
            outcome: Actual value.
            strategy_id: Strategy that initiated the action.
            scale: Scale factor for normalization.
            context_snapshot: System state at action time.

        Returns:
            AAREvent with computed error metrics.
        """
        raw_error = outcome - prediction
        abs_error = abs(raw_error)

        # Determine error sign (positive = outcome better than prediction)
        if abs_error < 1e-9:
            error_sign = 0
        elif raw_error > 0:
            error_sign = 1  # outcome > prediction = better
        else:
            error_sign = -1  # outcome < prediction = worse

        # Normalize error magnitude using tanh scaling
        import math

        safe_scale = max(abs(scale), 1e-9)
        error_magnitude = abs(math.tanh(raw_error / safe_scale))

        return cls(
            action_id=action_id,
            prediction=prediction,
            outcome=outcome,
            error=raw_error,
            error_sign=error_sign,
            error_magnitude=error_magnitude,
            strategy_id=strategy_id,
            context_snapshot=context_snapshot or {},
        )


