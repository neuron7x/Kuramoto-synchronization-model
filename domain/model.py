@dataclass(frozen=True, slots=True)
class ActionDecision:
    """Decision about what action the system should take.

    Represents the output of the decision loop after processing
    strategy signals through risk management. Immutable to ensure
    audit trail integrity.

    Attributes:
        action_id: Unique action identifier.
        action_type: Type of action to take.
        symbol: Instrument symbol.
        quantity: Action quantity.
        price: Target price (for limit orders).
        signal_id: Source signal that triggered this decision.
        strategy_id: Strategy that generated the source signal.
        confidence: Confidence in the decision.
        risk_score: Risk assessment score.
        rationale: Explanation for the decision.
        decided_at: When decision was made.
        metadata: Additional decision metadata.

    Raises:
        ValueError: If quantity is negative.
    """

    action_id: str
    action_type: ActionType
    symbol: str
    quantity: float = 0.0
    price: float | None = None
    signal_id: SignalId | None = None
    strategy_id: StrategyId | None = None
    confidence: float = 1.0
    risk_score: float = 0.0
    rationale: str | None = None
    decided_at: datetime = field(default_factory=_utc_now)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.symbol:
            raise ValueError("symbol must be provided")
        if self.quantity < 0:
            raise ValueError("quantity cannot be negative")
        if self.price is not None and self.price <= 0:
            raise ValueError("price must be positive when provided")
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("confidence must be between 0 and 1")
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "decided_at", _ensure_utc(self.decided_at))

    @property
    def is_entry(self) -> bool:
        """Return True if action is an entry (buy/sell/scale_in)."""
        return self.action_type in (ActionType.BUY, ActionType.SELL, ActionType.SCALE_IN)

    @property
    def is_exit(self) -> bool:
        """Return True if action is an exit (close/reduce/scale_out)."""
        return self.action_type in (
            ActionType.CLOSE,
            ActionType.REDUCE,
            ActionType.SCALE_OUT,
        )


