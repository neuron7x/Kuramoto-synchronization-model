@dataclass(frozen=True, slots=True)
class OrderRequest:
    """Request to create a new order.

    This represents the intent to place an order before it is submitted
    to the execution layer. Immutable to ensure request integrity.

    Attributes:
        symbol: Instrument symbol (e.g., "BTCUSD").
        side: Order side ("buy" or "sell").
        quantity: Order quantity. Must be positive.
        order_type: Type of order (market, limit, etc.).
        price: Limit price (required for limit orders).
        stop_price: Stop trigger price (for stop orders).
        strategy_id: ID of strategy that generated this request.
        signal_id: ID of signal that triggered this order.
        metadata: Additional order metadata.
        created_at: Timestamp when request was created.

    Raises:
        ValueError: If quantity is not positive or if limit order has no price.
    """

    symbol: str
    side: ActionType
    quantity: float
    order_type: OrderRequestType = OrderRequestType.MARKET
    price: float | None = None
    stop_price: float | None = None
    strategy_id: StrategyId | None = None
    signal_id: SignalId | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)
    created_at: datetime = field(default_factory=_utc_now)

    def __post_init__(self) -> None:
        if self.quantity <= 0:
            raise ValueError("quantity must be positive")
        if self.order_type == OrderRequestType.LIMIT and self.price is None:
            raise ValueError("limit orders require a price")
        if self.price is not None and self.price <= 0:
            raise ValueError("price must be positive when provided")
        if self.stop_price is not None and self.stop_price <= 0:
            raise ValueError("stop_price must be positive when provided")
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "created_at", _ensure_utc(self.created_at))


@dataclass(frozen=True, slots=True)
class OrderExecution:
    """Represents an executed order fill.

    Captures the details of a single fill event for an order. Multiple
    fills can occur for a single order (partial fills).

    Attributes:
        order_id: ID of the order being filled.
        symbol: Instrument symbol.
        side: Execution side.
        quantity: Filled quantity.
        price: Execution price.
        fee: Transaction fee.
        fee_currency: Currency of the fee.
        executed_at: Timestamp of execution.
        metadata: Additional execution metadata.

    Raises:
        ValueError: If quantity or price is not positive.
    """

    order_id: OrderId
    symbol: str
    side: ActionType
    quantity: float
    price: float
    fee: float = 0.0
    fee_currency: str = "USD"
    executed_at: datetime = field(default_factory=_utc_now)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.quantity <= 0:
            raise ValueError("quantity must be positive")
        if self.price <= 0:
            raise ValueError("price must be positive")
        if self.fee < 0:
            raise ValueError("fee cannot be negative")
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "executed_at", _ensure_utc(self.executed_at))


@dataclass(frozen=True, slots=True)
class Trade:
    """Completed trade with full execution details.

    A Trade represents a completed round-trip or partial position change,
    aggregating one or more order executions.

    Attributes:
        trade_id: Unique trade identifier.
        symbol: Instrument symbol.
        side: Trade side.
        entry_price: Average entry price.
        exit_price: Average exit price (None if position still open).
        quantity: Trade quantity.
        realized_pnl: Realized profit/loss.
        fees: Total fees paid.
        opened_at: When the trade was opened.
        closed_at: When the trade was closed (None if still open).
        strategy_id: Strategy that initiated this trade.
        metadata: Additional trade metadata.

    Raises:
        ValueError: If quantity is not positive or prices are invalid.
    """

    trade_id: TradeId
    symbol: str
    side: ActionType
    entry_price: float
    quantity: float
    exit_price: float | None = None
    realized_pnl: float = 0.0
    fees: float = 0.0
    opened_at: datetime = field(default_factory=_utc_now)
    closed_at: datetime | None = None
    strategy_id: StrategyId | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if self.quantity <= 0:
            raise ValueError("quantity must be positive")
        if self.entry_price <= 0:
            raise ValueError("entry_price must be positive")
        if self.exit_price is not None and self.exit_price <= 0:
            raise ValueError("exit_price must be positive when provided")
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "opened_at", _ensure_utc(self.opened_at))
        if self.closed_at is not None:
            object.__setattr__(self, "closed_at", _ensure_utc(self.closed_at))

    @property
    def is_closed(self) -> bool:
        """Return True if trade is closed."""
        return self.exit_price is not None and self.closed_at is not None


