from typing import Any, Mapping, NewType

# -----------------------------------------------------------------------------
# Strongly-typed ID aliases
# -----------------------------------------------------------------------------

OrderId = NewType("OrderId", str)
StrategyId = NewType("StrategyId", str)
TradeId = NewType("TradeId", str)
SignalId = NewType("SignalId", str)
PositionId = NewType("PositionId", str)


def generate_order_id() -> OrderId:
    """Generate a unique order ID."""
    return OrderId(f"ord_{uuid.uuid4().hex[:16]}")


def generate_trade_id() -> TradeId:
    """Generate a unique trade ID."""
    return TradeId(f"trd_{uuid.uuid4().hex[:16]}")


def generate_signal_id() -> SignalId:
    """Generate a unique signal ID."""
    return SignalId(f"sig_{uuid.uuid4().hex[:16]}")


