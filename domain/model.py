@dataclass(frozen=True, slots=True)
class StrategySignal:
    """Signal generated by a trading strategy.

    Represents a recommendation from a strategy about what action to take.
    Does not directly create orders - the decision loop processes signals
    through risk management before execution.

    Attributes:
        signal_id: Unique signal identifier.
        symbol: Instrument symbol.
        direction: Signal direction (long/short/flat).
        strength: Signal strength in range [0, 1].
        confidence: Confidence in signal in range [0, 1].
        strategy_id: ID of strategy that generated this signal.
        issued_at: When signal was issued.
        valid_until: When signal expires (None for no expiry).
        target_position: Target position size (normalized, -1 to 1).
        rationale: Human-readable explanation.
        metadata: Additional signal metadata.

    Raises:
        ValueError: If strength or confidence is out of range.
    """

    signal_id: SignalId
    symbol: str
    direction: SignalDirection
    strength: float = 1.0
    confidence: float = 1.0
    strategy_id: StrategyId | None = None
    issued_at: datetime = field(default_factory=_utc_now)
    valid_until: datetime | None = None
    target_position: float = 0.0
    rationale: str | None = None
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        if not self.symbol:
            raise ValueError("symbol must be provided")
        if not 0.0 <= self.strength <= 1.0:
            raise ValueError("strength must be between 0 and 1")
        if not 0.0 <= self.confidence <= 1.0:
            raise ValueError("confidence must be between 0 and 1")
        if not -1.0 <= self.target_position <= 1.0:
            raise ValueError("target_position must be between -1 and 1")
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "issued_at", _ensure_utc(self.issued_at))
        if self.valid_until is not None:
            object.__setattr__(self, "valid_until", _ensure_utc(self.valid_until))

    @property
    def is_expired(self) -> bool:
        """Check if signal has expired."""
        if self.valid_until is None:
            return False
        return _utc_now() > self.valid_until


@dataclass(frozen=True, slots=True)
class MarketDataSnapshot:
    """Snapshot of market data for strategy context.

    Provides current market state including prices, volumes, and
    derived indicators to strategies for decision making.

    Attributes:
        symbol: Instrument symbol.
        bid: Best bid price.
        ask: Best ask price.
        last: Last trade price.
        volume: Current period volume.
        timestamp: When data was captured.
        ohlc: OHLC data if available (open, high, low, close).
        indicators: Pre-computed indicator values.
        metadata: Additional market metadata.
    """

    symbol: str
    bid: float = 0.0
    ask: float = 0.0
    last: float = 0.0
    volume: float = 0.0
    timestamp: datetime = field(default_factory=_utc_now)
    ohlc: Mapping[str, float] = field(default_factory=dict)
    indicators: Mapping[str, float] = field(default_factory=dict)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        object.__setattr__(self, "ohlc", _freeze_mapping(self.ohlc))
        object.__setattr__(self, "indicators", _freeze_mapping(self.indicators))
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "timestamp", _ensure_utc(self.timestamp))

    @property
    def mid(self) -> float:
        """Calculate mid price from bid/ask."""
        if self.bid > 0 and self.ask > 0:
            return (self.bid + self.ask) / 2.0
        return self.last

    @property
    def spread(self) -> float:
        """Calculate bid-ask spread."""
        if self.bid > 0 and self.ask > 0:
            return self.ask - self.bid
        return 0.0


@dataclass(frozen=True, slots=True)
class StrategyContext:
    """Context provided to strategies for decision making.

    Aggregates all information a strategy needs to generate signals:
    current portfolio state, market data, and operational mode.

    Attributes:
        mode: Current environment mode (backtest/paper/live).
        portfolio: Current portfolio state.
        market_data: Mapping of symbol to market data snapshot.
        timestamp: Current evaluation timestamp.
        metadata: Additional context metadata.
    """

    mode: EnvironmentMode
    portfolio: PortfolioState
    market_data: Mapping[str, MarketDataSnapshot] = field(default_factory=dict)
    timestamp: datetime = field(default_factory=_utc_now)
    metadata: Mapping[str, Any] = field(default_factory=dict)

    def __post_init__(self) -> None:
        object.__setattr__(self, "market_data", _freeze_mapping(self.market_data))
        object.__setattr__(self, "metadata", _freeze_mapping(self.metadata))
        object.__setattr__(self, "timestamp", _ensure_utc(self.timestamp))

    def get_market_data(self, symbol: str) -> MarketDataSnapshot | None:
        """Get market data for a symbol."""
        return self.market_data.get(symbol)

    def get_position(self, symbol: str) -> PositionState | None:
        """Get current position for a symbol."""
        return self.portfolio.position_for(symbol)


