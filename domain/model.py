"""Unified domain model for TradePulse trading system.

This module provides the canonical domain entities used across all layers
of the TradePulse system: backtest, paper trading, and live execution.
All modules should use these types to ensure consistency and type safety.

Core Entities:
    - OrderRequest: Request to create a new order
    - OrderExecution: Represents an executed order fill
    - Trade: Completed trade with full execution details
    - PositionState: Current state of a position
    - PortfolioState: Snapshot of portfolio state
    - StrategySignal: Signal generated by a strategy
    - StrategyContext: Context passed to strategy for decision making
    - ActionDecision: Decision about what action to take
    - AAREvent: Acceptor of Action Result event for feedback loop

Type Aliases:
    - OrderId, StrategyId, TradeId, SignalId: Strongly-typed string IDs

See docs/DOMAIN_MODEL.md for full specification.
"""

from __future__ import annotations

import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
