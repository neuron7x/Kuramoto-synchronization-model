@dataclass(frozen=True, slots=True)
class PositionState:
    """Current state of a position for a single instrument.

    Represents the current exposure and P&L for one symbol. Immutable
    snapshot that can be used safely across threads.

    Attributes:
        symbol: Instrument symbol.
        quantity: Position quantity (positive for long, negative for short).
        entry_price: Average entry price.
        current_price: Latest market price.
        unrealized_pnl: Current unrealized P&L.
        realized_pnl: Cumulative realized P&L.
        currency: Position currency.
        updated_at: Last update timestamp.

    Raises:
        ValueError: If entry_price or current_price is invalid.
    """

    symbol: str
    quantity: float = 0.0
    entry_price: float = 0.0
    current_price: float = 0.0
    unrealized_pnl: float = 0.0
    realized_pnl: float = 0.0
    currency: str = "USD"
    updated_at: datetime = field(default_factory=_utc_now)

    def __post_init__(self) -> None:
        if not self.symbol:
            raise ValueError("symbol must be provided")
        if self.quantity != 0 and self.entry_price <= 0:
            raise ValueError("entry_price must be positive when position is open")
        if self.current_price < 0:
            raise ValueError("current_price cannot be negative")
        object.__setattr__(self, "updated_at", _ensure_utc(self.updated_at))

    @property
    def is_long(self) -> bool:
        """Return True if position is long."""
        return self.quantity > 0

    @property
    def is_short(self) -> bool:
        """Return True if position is short."""
        return self.quantity < 0

    @property
    def is_flat(self) -> bool:
        """Return True if position is flat."""
        return abs(self.quantity) < 1e-9

    @property
    def market_value(self) -> float:
        """Return current market value of position."""
        return abs(self.quantity) * self.current_price


@dataclass(frozen=True, slots=True)
class PortfolioState:
    """Snapshot of portfolio state at a point in time.

    Provides a complete view of portfolio including all positions,
    cash, and aggregate metrics. Immutable to ensure thread safety.

    Attributes:
        positions: Mapping of symbol to PositionState.
        cash: Available cash balance.
        equity: Total portfolio equity (cash + position values).
        peak_equity: Peak equity for drawdown calculation.
        margin_used: Total margin currently used.
        volatility: Portfolio volatility estimate.
        currency: Base currency.
        timestamp: When snapshot was taken.

    Raises:
        ValueError: If equity values are invalid.
    """

    positions: Mapping[str, PositionState] = field(default_factory=dict)
    cash: float = 0.0
    equity: float = 0.0
    peak_equity: float = 0.0
    margin_used: float = 0.0
    volatility: float = 0.0
    currency: str = "USD"
    timestamp: datetime = field(default_factory=_utc_now)

    def __post_init__(self) -> None:
        object.__setattr__(self, "positions", _freeze_mapping(self.positions))
        object.__setattr__(self, "timestamp", _ensure_utc(self.timestamp))

    @property
    def drawdown(self) -> float:
        """Calculate current drawdown from peak equity."""
        if self.peak_equity <= 0:
            return 0.0
        return max(0.0, (self.peak_equity - self.equity) / self.peak_equity)

    @property
    def net_exposure(self) -> float:
        """Calculate net exposure across all positions."""
        return sum(
            pos.quantity * pos.current_price for pos in self.positions.values()
        )

    @property
    def gross_exposure(self) -> float:
        """Calculate gross exposure across all positions."""
        return sum(
            abs(pos.quantity * pos.current_price) for pos in self.positions.values()
        )

    def position_for(self, symbol: str) -> PositionState | None:
        """Get position state for a symbol."""
        return self.positions.get(symbol)


